_BY_CODE = {code: (fr, en) for code, fr, en in LANGUAGES}


def name(code: str | None, ui: str) -> str:
    if code is None:
        return "Détection automatique" if ui == "fr" else "Auto-detect"
    fr, en = _BY_CODE.get(code, (code, code))
    return fr if ui == "fr" else en


def short(code: str | None) -> str:
    return "AUTO" if code is None else code.upper()
